// Защита аккумулятора на голове (ТЗ §3.4). Главный — со-процессор: он меряет батарею и решает.
//  "B,2,mV" -> ответ SLEEP, звук и Wi-Fi выкл, экран «БАТАРЕЯ СЕЛА», мьюты держатся во сне,
//              глубокий сон с пробуждением по LOW на RX18 (со-процессор проснулся) или T_IRQ17 (касание).
//  "G,mV"   -> включили тумблером на севшем: 5 с кнопка «ВКЛЮЧИТЬ» (или сенсор 2 -> "F") -> FORCE.
//  Запасной путь: связь пропала > 30 с при батарее < 3.15 В -> спать.
#pragma once

#define BAT_NONE_MV   2500     // ниже — аккума нет (стенд от USB)
#define BAT_LOW_MV    3300     // предупреждение LOW BAT

void power_boot_gate(void);         // самое начало app_main: проснулись из-за аккума — может, спать дальше
void power_bat_shutdown(int mv);    // не возвращается
void power_grace(int mv);           // окно «ВКЛЮЧИТЬ» (блокирует до 5 с)
void power_tick(void);              // раз в секунду
